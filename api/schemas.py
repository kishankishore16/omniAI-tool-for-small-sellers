"""
OmniAI — Pydantic Schemas
Shared data models used across agents, API, and database layers.
"""

from __future__ import annotations

from datetime import datetime
from typing import Optional

from pydantic import BaseModel, Field


# ══════════════════════════════════════════════════════════════════════
# Agent Output Models
# ══════════════════════════════════════════════════════════════════════


class ProductFeatures(BaseModel):
    """Structured features extracted from a product image by the Vision Agent."""

    product_type: str = Field(
        ..., description="Category: jewelry, hamper, accessory, clothing, etc."
    )
    materials: list[str] = Field(
        default_factory=list, description="Detected materials (e.g., gold, silk)"
    )
    style: str = Field(default="modern", description="Design style descriptor")
    color_palette: list[str] = Field(
        default_factory=list, description="Dominant colors as hex codes"
    )
    style_complexity: int = Field(
        default=5, ge=1, le=10, description="Design complexity score 1-10"
    )
    weight_category: str = Field(
        default="medium", description="Estimated: light / medium / heavy"
    )
    quality_indicators: list[str] = Field(
        default_factory=list,
        description="Visual quality cues (e.g., polished, handcrafted)",
    )
    target_audience: str = Field(
        default="general", description="Intended customer segment"
    )


class ProductCopy(BaseModel):
    """SEO-optimized marketing copy generated by the Copywriter Agent."""

    title: str = Field(..., description="Compelling product title")
    description: str = Field(
        ..., description="SEO-optimized description (150-300 words)"
    )
    seo_tags: list[str] = Field(
        default_factory=list, description="10-15 search-friendly tags"
    )
    key_selling_points: list[str] = Field(
        default_factory=list, description="3-5 bullet selling points"
    )


class PriceResult(BaseModel):
    """Dynamic pricing prediction from the Pricing Agent."""

    predicted_price: float = Field(..., description="Optimal price in USD")
    confidence_low: float = Field(..., description="Lower confidence bound")
    confidence_high: float = Field(..., description="Upper confidence bound")
    price_factors: dict[str, float] = Field(
        default_factory=dict,
        description="Feature contribution breakdown for explainability",
    )


# ══════════════════════════════════════════════════════════════════════
# Product Record (Database)
# ══════════════════════════════════════════════════════════════════════


class ProductRecord(BaseModel):
    """Complete product record stored in the catalog database."""

    id: Optional[int] = None
    name: str
    description: str
    seo_tags: list[str] = Field(default_factory=list)
    key_selling_points: list[str] = Field(default_factory=list)
    price: float
    confidence_low: float = 0.0
    confidence_high: float = 0.0
    features: ProductFeatures
    price_factors: dict[str, float] = Field(default_factory=dict)
    image_path: str = ""
    created_at: Optional[str] = None


# ══════════════════════════════════════════════════════════════════════
# API Request / Response Models
# ══════════════════════════════════════════════════════════════════════


class ProcessingStep(BaseModel):
    """Tracks a single step in the multi-agent pipeline."""

    agent: str
    status: str = "completed"  # completed | failed | skipped
    duration_ms: float = 0.0
    details: str = ""


class ProductUploadResponse(BaseModel):
    """Response returned after processing a product image through the pipeline."""

    success: bool
    product: ProductRecord
    processing_steps: list[ProcessingStep] = Field(default_factory=list)


class ChatRequest(BaseModel):
    """Customer chat message sent to the RAG agent."""

    message: str = Field(..., min_length=1, max_length=2000)
    conversation_id: Optional[str] = None


class SourceProduct(BaseModel):
    """A product referenced as a source in a RAG response."""

    id: int
    name: str
    price: float
    relevance_score: float = Field(ge=0.0, le=1.0)


class ChatResponse(BaseModel):
    """RAG agent response with answer and source products."""

    answer: str
    source_products: list[SourceProduct] = Field(default_factory=list)
    conversation_id: str


class ProductListResponse(BaseModel):
    """Paginated list of products."""

    products: list[ProductRecord]
    total: int
    page: int = 1
    per_page: int = 20


class AnalyticsResponse(BaseModel):
    """Dashboard analytics payload."""

    total_products: int
    avg_price: float
    price_distribution: list[dict]
    category_breakdown: list[dict]
    feature_importance: dict[str, float]
    model_metrics: dict[str, float]
    recent_products: list[ProductRecord]


class HealthResponse(BaseModel):
    """API health check response."""

    status: str = "ok"
    version: str = "1.0.0"
    gemini_available: bool = False
    model_loaded: bool = False
    products_count: int = 0
